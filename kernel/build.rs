//! カーネルのビルドスクリプト。
//!
//! 1. リンカスクリプト (linker.ld) を指定する。
//! 2. 256 個の割り込みエントリスタブ (アセンブリ) を生成する。
//!    `kernel/src/arch/x86_64/trap.rs` が `global_asm!(include_str!(...))` で取り込む。

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// CPU がエラーコードを積む例外ベクタ (Intel SDM Vol.3 Table 6-1)。
const VECTORS_WITH_ERROR_CODE: [u32; 10] = [8, 10, 11, 12, 13, 14, 17, 21, 29, 30];

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo");
    let target = env::var("TARGET").expect("TARGET is set by cargo");

    if target == "x86_64-unknown-none" {
        println!("cargo:rustc-link-arg-bins=-T{manifest_dir}/linker.ld");
    } else {
        // ホスト向けにビルドしようとした場合は分かりやすく失敗させる
        println!("cargo:warning=yumekawa-kernel は x86_64-unknown-none 専用です (TARGET={target})");
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    fs::write(out_dir.join("interrupt_vectors.s"), interrupt_vectors())
        .expect("failed to write interrupt_vectors.s");

    println!("cargo:rerun-if-changed=linker.ld");
    println!("cargo:rerun-if-changed=build.rs");
}

/// 各ベクタのスタブ: (エラーコードが無ければ 0 を積み) ベクタ番号を積んで共通処理へ飛ぶ。
/// 末尾にスタブのアドレス表 `yk_interrupt_vectors` を置く。
fn interrupt_vectors() -> String {
    let mut s = String::new();
    s.push_str("/* generated by kernel/build.rs — do not edit */\n");
    s.push_str(".section .text.yk_interrupt_vectors, \"ax\", @progbits\n");
    for v in 0..256u32 {
        writeln!(s, ".p2align 4").unwrap();
        writeln!(s, "yk_interrupt_vector_{v}:").unwrap();
        if !VECTORS_WITH_ERROR_CODE.contains(&v) {
            writeln!(s, "    push 0").unwrap();
        }
        writeln!(s, "    push {v}").unwrap();
        writeln!(s, "    jmp yk_interrupt_common").unwrap();
    }
    s.push_str(".section .rodata.yk_interrupt_vectors, \"a\", @progbits\n");
    s.push_str(".p2align 3\n.global yk_interrupt_vectors\nyk_interrupt_vectors:\n");
    for v in 0..256u32 {
        writeln!(s, "    .quad yk_interrupt_vector_{v}").unwrap();
    }
    s
}
